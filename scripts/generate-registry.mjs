#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import process from "node:process";
import Ajv2020 from "ajv/dist/2020.js";
import { parse } from "yaml";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const registryPath = path.join(repositoryRoot, "protocol", "parameter_registry.yaml");
const schemaPath = path.join(repositoryRoot, "schemas", "peak_parameter.schema.json");
const outputPath = path.join(
  repositoryRoot,
  "packages",
  "parameter-registry",
  "src",
  "generated.ts",
);

const [registryText, schemaText] = await Promise.all([
  readFile(registryPath, "utf8"),
  readFile(schemaPath, "utf8"),
]);

const registry = parse(registryText);
const schema = JSON.parse(schemaText);
const errors = [];

if (!registry || typeof registry !== "object" || !Array.isArray(registry.parameters)) {
  errors.push("registry root must contain a parameters array");
}

const ajv = new Ajv2020({
  allErrors: true,
  allowUnionTypes: true,
  strict: false,
});
const validateParameter = ajv.compile(schema);
const ids = new Set();
const bindings = new Map();

for (const [index, parameter] of (registry.parameters ?? []).entries()) {
  const valid = validateParameter(parameter);
  if (!valid) {
    const detail = validateParameter.errors
      ?.map((error) => `${error.instancePath || "/"} ${error.message}`)
      .join("; ");
    errors.push(`parameter[${index}] ${parameter?.id ?? "<missing>"}: ${detail}`);
  }

  if (!parameter?.id || ids.has(parameter.id)) {
    errors.push(`duplicate or missing parameter id: ${String(parameter?.id)}`);
  } else {
    ids.add(parameter.id);
  }

  const bindingKey = getBindingKey(parameter?.binding);
  if (bindingKey) {
    const prior = bindings.get(bindingKey);
    if (prior) {
      errors.push(`duplicate binding ${bindingKey}: ${prior}, ${parameter.id}`);
    } else {
      bindings.set(bindingKey, parameter.id);
    }
  }

  if (parameter?.gates?.live_write_enabled !== false) {
    errors.push(`${parameter?.id ?? `parameter[${index}]`}: live writes must be disabled`);
  }

  if (
    parameter?.scope === "global" &&
    !parameter.id.startsWith("settings.")
  ) {
    errors.push(`${parameter.id}: global values must use the settings namespace`);
  }
}

if (errors.length > 0) {
  for (const error of errors) {
    console.error(`ERROR: ${error}`);
  }
  process.exitCode = 1;
} else {
  const metadata = {
    schema_version: registry.schema_version,
    device_profile: registry.device_profile,
    generated_on: registry.generated_on,
    policy: registry.policy,
  };
  const generated = `/* eslint-disable */
// @generated by scripts/generate-registry.mjs. Do not edit by hand.
import type { ParameterDefinition, RegistryMetadata } from "./types";

export const REGISTRY_METADATA = ${JSON.stringify(metadata, null, 2)} as const satisfies RegistryMetadata;

export const PARAMETER_REGISTRY = ${JSON.stringify(registry.parameters, null, 2)} as const satisfies readonly ParameterDefinition[];

export type ParameterId = (typeof PARAMETER_REGISTRY)[number]["id"];

export const PARAMETER_BY_ID: ReadonlyMap<ParameterId, (typeof PARAMETER_REGISTRY)[number]> =
  new Map(PARAMETER_REGISTRY.map((parameter) => [parameter.id, parameter]));
`;

  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = await readFile(outputPath, "utf8");
    } catch {
      // The comparison below emits the actionable message.
    }
    if (current !== generated) {
      console.error(
        "ERROR: generated registry is missing or stale; run `npm run registry:generate`.",
      );
      process.exitCode = 1;
    } else {
      console.log(
        `OK: ${ids.size} parameters; ${bindings.size} unique mapped bindings; generated registry is current.`,
      );
    }
  } else {
    await writeFile(outputPath, generated, "utf8");
    console.log(
      `Generated ${path.relative(repositoryRoot, outputPath)} from ${ids.size} parameters.`,
    );
  }
}

function getBindingKey(binding) {
  if (!binding || typeof binding !== "object") {
    return null;
  }
  switch (binding.kind) {
    case "cc":
      return `cc:${binding.controller}`;
    case "cc_pair":
      return `cc_pair:${binding.controllers?.join(":")}`;
    case "nrpn":
      return `nrpn:${binding.msb}:${binding.lsb}`;
    default:
      return null;
  }
}
